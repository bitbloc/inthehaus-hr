-- 7. Policies & RLS Configuration
ALTER TABLE announcements ENABLE ROW LEVEL SECURITY;
ALTER TABLE job_applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE payroll_deductions ENABLE ROW LEVEL SECURITY;
ALTER TABLE payroll_config ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Enable read access for all users" ON announcements FOR SELECT USING (true);
CREATE POLICY "Enable insert/update for authenticated users only" ON announcements FOR ALL USING (auth.role() = 'authenticated');

CREATE POLICY "Allow public insert for job applications" ON job_applications FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow authenticated read job applications" ON job_applications FOR SELECT USING (auth.role() = 'authenticated');

CREATE POLICY "Allow read payroll deductions for all" ON payroll_deductions FOR SELECT USING (true);
CREATE POLICY "Allow modify payroll deductions for authenticated" ON payroll_deductions FOR ALL USING (auth.role() = 'authenticated');

CREATE POLICY "Allow read payroll config for all" ON payroll_config FOR SELECT USING (true);
CREATE POLICY "Allow modify payroll config for authenticated" ON payroll_config FOR ALL USING (auth.role() = 'authenticated');
