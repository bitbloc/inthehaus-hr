-- 9. Roster Transactions (ตารางกะงานจริงรายวัน)
CREATE TABLE IF NOT EXISTS roster_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    date DATE NOT NULL,
    shift_id BIGINT REFERENCES shifts(id) ON DELETE SET NULL,
    custom_start_time TEXT,
    custom_end_time TEXT,
    slot_type TEXT DEFAULT 'MAIN',
    is_off BOOLEAN DEFAULT FALSE,
    status TEXT DEFAULT 'PUBLISHED',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_roster_tx_date ON roster_transactions(date);
CREATE INDEX IF NOT EXISTS idx_roster_tx_emp ON roster_transactions(employee_id);
ALTER TABLE roster_transactions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow read roster_transactions for all" ON roster_transactions FOR SELECT USING (true);
CREATE POLICY "Allow modify roster_transactions for authenticated" ON roster_transactions FOR ALL USING (auth.role() = 'authenticated');

-- 10. Weekly Template Schedules (ตารางงานเทมเพลตประจำสัปดาห์)
CREATE TABLE IF NOT EXISTS employee_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    day_of_week INTEGER NOT NULL, -- 0 (Sun) to 6 (Sat)
    shift_id BIGINT REFERENCES shifts(id) ON DELETE SET NULL,
    is_off BOOLEAN DEFAULT FALSE,
    custom_start_time TEXT,
    custom_end_time TEXT,
    slot_type TEXT DEFAULT 'MAIN',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

ALTER TABLE employee_schedules ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow read employee_schedules for all" ON employee_schedules FOR SELECT USING (true);
CREATE POLICY "Allow modify employee_schedules for authenticated" ON employee_schedules FOR ALL USING (auth.role() = 'authenticated');

-- 11. Leave Requests Table (คำขอลาหยุดงาน)
CREATE TABLE IF NOT EXISTS leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    leave_date DATE NOT NULL,
    leave_type TEXT NOT NULL DEFAULT 'sick',
    reason TEXT,
    status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    replacement_employee_id BIGINT REFERENCES employees(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_leave_requests_date ON leave_requests(leave_date);
ALTER TABLE leave_requests ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow read leave_requests for all" ON leave_requests FOR SELECT USING (true);
CREATE POLICY "Allow modify leave_requests for authenticated" ON leave_requests FOR ALL USING (auth.role() = 'authenticated');

