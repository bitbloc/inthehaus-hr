-- 1. Announcements Table
CREATE TABLE IF NOT EXISTS announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message TEXT NOT NULL,
  priority INTEGER DEFAULT 1,
  expires_at TIMESTAMP WITH TIME ZONE,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Add Mood & Note columns to attendance_logs
ALTER TABLE attendance_logs 
ADD COLUMN IF NOT EXISTS mood_status TEXT,
ADD COLUMN IF NOT EXISTS mood_note TEXT;

-- 3. Job Applications Table
CREATE TABLE IF NOT EXISTS job_applications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    full_name TEXT NOT NULL,
    position_applied TEXT NOT NULL,
    email TEXT,
    phone TEXT,
    resume_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    status TEXT DEFAULT 'Pending' CHECK (status IN ('Pending', 'Reviewing', 'Interviewed', 'Rejected', 'Hired')),
    metadata JSONB
);

-- 4. Staff Table Expansion (employees)
ALTER TABLE employees 
ADD COLUMN IF NOT EXISTS is_active BOOLEAN DEFAULT TRUE,
ADD COLUMN IF NOT EXISTS name_en TEXT,
ADD COLUMN IF NOT EXISTS nickname TEXT,
ADD COLUMN IF NOT EXISTS phone TEXT,
ADD COLUMN IF NOT EXISTS email TEXT,
ADD COLUMN IF NOT EXISTS address TEXT,
ADD COLUMN IF NOT EXISTS id_card TEXT, 
ADD COLUMN IF NOT EXISTS employment_status TEXT CHECK (employment_status IN ('Probation', 'Fulltime', 'Contract', 'Part-time', 'Resigned', 'Suspended', 'Vacation')),
