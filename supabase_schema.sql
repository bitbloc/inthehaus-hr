-- 5. Payroll Deductions & Adjustments Table
CREATE TABLE IF NOT EXISTS payroll_deductions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    month TEXT NOT NULL, -- e.g. '2026-09'
    amount NUMERIC NOT NULL,
    is_percentage BOOLEAN DEFAULT FALSE,
    reason TEXT,
    type TEXT DEFAULT 'deduction' CHECK (type IN ('deduction', 'bonus', 'advance')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_payroll_deductions_month ON payroll_deductions(month);
CREATE INDEX IF NOT EXISTS idx_payroll_deductions_emp ON payroll_deductions(employee_id);

